const pool = require('../config/db');

/*
  ── FARMER LEDGER ──────────────────────────────────────────────────────────
  Builds a unified, running-balance ledger for a farmer (seller) out of the
  existing transaction tables. There is no new table/migration required.

  DESIGN NOTES / ASSUMPTIONS (read this before changing the logic):

  Ledger balance = cumulative (Credit − Debit) = cash the dairy currently
  owes the farmer.

  Rows pulled in, one ledger line per source row:
    • milk_entries                                  → CREDIT "Milk Sale"
    • cash_advance   type = 'given'                 → DEBIT  "Advance Given"
    • cash_advance   type = 'received'               → CREDIT "Advance Repayment"
        (ONLY rows NOT auto-generated by markPaid — those carry the remark
        "Installment cut for ..." and are represented instead by the bill's
        own "Advance Installment Recovered" line below, to avoid double
        counting the same rupee twice.)
    • seller_deposits type = 'debit' (refund)         → CREDIT "Deposit Refunded"
        (type = 'credit' deposits are always auto-generated by markPaid and
        are represented by the bill's "Deposit Held" line instead.)
    • product_sales / cattle_feed_sales / walkin_sales (seller_id present)
                                                      → DEBIT  "Product/Feed/Walk-in Purchase"
    • seller_payments (rows where paid_at IS NOT NULL, i.e. a settled bill)
      contributes up to three DEBIT lines, all tagged with that bill's number:
         "Deposit Held"                  = deposit_amount
         "Advance Installment Recovered" = installment_cut
         "Cash Paid"                     = cash_paid

  Why this nets out correctly: for any settled bill,
     milk_amount = deposit_amount + installment_cut
                 + product_deduction + walkin_deduction + cattle_feed_deduction
                 + cash_paid
  Since product/walkin/cattle-feed deductions are already covered by their
  own raw transaction rows, the three bill-derived lines above plus those
  raw rows exactly balance the milk credit for a fully paid cycle. Any milk
  collected but not yet billed simply stays as a positive running balance
  (money owed to the farmer that hasn't been settled yet).
*/

// ── helpers ──────────────────────────────────────────────────────────────

const TYPE_LABELS = {
    milk_sale: 'Milk Sale',
    advance_given: 'Advance Given',
    advance_repayment: 'Advance Repayment',
    deposit_taken: 'Deposit Taken',
    deposit_refund: 'Deposit Refunded',
    deposit_withdrawn: 'Deposit Withdrawn',
    product_purchase: 'Product Purchase',
    cattle_feed_purchase: 'Cattle Feed Purchase',
    walkin_purchase: 'Milk Purchase (Walk-in)',
    deposit_held: 'Deposit Held',
    advance_recovered: 'Advance Installment Recovered',
    cash_paid: 'Payment Settled',
};

const round2 = (n) => Math.round((parseFloat(n) || 0) * 100) / 100;

// Fetches every raw row (across categories) for one centre, optionally
// scoped to a single seller and/or an upper date bound. Returns a flat,
// un-ordered array of { seller_id, seller_code, name, ts, txn_date, type,
// description, debit, credit, payment_mode, reference_no, operator_name }.
async function fetchRawLedgerRows(centreId, { sellerId = null, uptoDate = null } = {}) {
    const rows = [];

    // 1. Milk entries → CREDIT
    {
        const args = [centreId];
        let sql = `
            SELECT me.entry_id AS id, me.seller_id, s.name, s.seller_code,
                   me.entry_date, me.entry_time, me.shift, me.milk_type,
                   me.quantity, me.fat, me.snf, me.total_amount,
                   o.name AS operator_name
            FROM milk_entries me
            JOIN sellers s ON s.seller_id = me.seller_id
            LEFT JOIN operators o ON o.operator_id = me.operator_id
            WHERE me.centre_id = ?`;
        if (sellerId) { sql += ' AND me.seller_id = ?'; args.push(sellerId); }
        if (uptoDate) { sql += ' AND me.entry_date <= ?'; args.push(uptoDate); }
        const [milk] = await pool.query(sql, args);
        for (const m of milk) {
            rows.push({
                seller_id: m.seller_id, seller_code: m.seller_code, name: m.name,
                ts: m.entry_time || `${m.entry_date}`,
                txn_date: m.entry_date,
                type: 'milk_sale',
                description: `Milk Collection · ${m.shift} · ${m.milk_type} · ${parseFloat(m.quantity).toFixed(2)}L @ Fat ${parseFloat(m.fat).toFixed(1)}/SNF ${parseFloat(m.snf).toFixed(1)}`,
                debit: 0,
                credit: round2(m.total_amount),
                payment_mode: '—',
                reference_no: `MILK-${m.id}`,
                operator_name: m.operator_name || 'Admin',
            });
        }
    }

    // 2. Cash advance given → DEBIT
    {
        const args = [centreId];
        let sql = `
            SELECT ca.id, ca.seller_id, s.name, s.seller_code,
                   ca.transaction_date, ca.created_at, ca.amount, ca.remarks,
                   o.name AS operator_name
            FROM cash_advance ca
            JOIN sellers s ON s.seller_id = ca.seller_id
            LEFT JOIN operators o ON o.operator_id = ca.operator_id
            WHERE ca.centre_id = ? AND ca.type = 'given'`;
        if (sellerId) { sql += ' AND ca.seller_id = ?'; args.push(sellerId); }
        if (uptoDate) { sql += ' AND ca.transaction_date <= ?'; args.push(uptoDate); }
        const [adv] = await pool.query(sql, args);
        for (const a of adv) {
            rows.push({
                seller_id: a.seller_id, seller_code: a.seller_code, name: a.name,
                ts: a.created_at || a.transaction_date,
                txn_date: a.transaction_date,
                type: 'advance_given',
                description: a.remarks || 'Cash advance given',
                debit: round2(a.amount),
                credit: 0,
                payment_mode: 'Cash',
                reference_no: `ADV-${a.id}`,
                operator_name: a.operator_name || 'Admin',
            });
        }
    }

    // 3. Cash advance received directly from farmer (manual only) → CREDIT
    {
        const args = [centreId];
        let sql = `
            SELECT ca.id, ca.seller_id, s.name, s.seller_code,
                   ca.transaction_date, ca.created_at, ca.amount, ca.remarks,
                   o.name AS operator_name
            FROM cash_advance ca
            JOIN sellers s ON s.seller_id = ca.seller_id
            LEFT JOIN operators o ON o.operator_id = ca.operator_id
            WHERE ca.centre_id = ? AND ca.type = 'received'
              AND (ca.remarks IS NULL OR ca.remarks NOT LIKE 'Installment cut for%')`;
        if (sellerId) { sql += ' AND ca.seller_id = ?'; args.push(sellerId); }
        if (uptoDate) { sql += ' AND ca.transaction_date <= ?'; args.push(uptoDate); }
        const [adv] = await pool.query(sql, args);
        for (const a of adv) {
            rows.push({
                seller_id: a.seller_id, seller_code: a.seller_code, name: a.name,
                ts: a.created_at || a.transaction_date,
                txn_date: a.transaction_date,
                type: 'advance_repayment',
                description: a.remarks || 'Advance repaid by farmer',
                debit: 0,
                credit: round2(a.amount),
                payment_mode: 'Cash',
                reference_no: `ADV-${a.id}`,
                operator_name: a.operator_name || 'Admin',
            });
        }
    }

    // 4. Deposit refunds (manual, type='debit') → CREDIT
    // 4. Manual deposit debits (type='debit') → split by category:
    //    'refund'     → CREDIT "Deposit Refunded"   (reverses a bill-held deposit)
    //    'withdrawal' → DEBIT  "Deposit Withdrawn"  (reverses a manually-taken deposit)
    //    Legacy rows with category=NULL are treated as 'refund'.
    {
        const args = [centreId];
        let sql = `
            SELECT sd.id, sd.seller_id, s.name, s.seller_code,
                   sd.transaction_date, sd.created_at, sd.amount, sd.remarks,
                   sd.category, o.name AS operator_name
            FROM seller_deposits sd
            JOIN sellers s ON s.seller_id = sd.seller_id
            LEFT JOIN operators o ON o.operator_id = sd.operator_id
            WHERE sd.centre_id = ? AND sd.type = 'debit'`;
        if (sellerId) { sql += ' AND sd.seller_id = ?'; args.push(sellerId); }
        if (uptoDate) { sql += ' AND sd.transaction_date <= ?'; args.push(uptoDate); }
        const [dep] = await pool.query(sql, args);
        for (const d of dep) {
            const isWithdrawal = d.category === 'withdrawal';
            rows.push({
                seller_id: d.seller_id, seller_code: d.seller_code, name: d.name,
                ts: d.created_at || d.transaction_date,
                txn_date: d.transaction_date,
                type: isWithdrawal ? 'deposit_withdrawn' : 'deposit_refund',
                description: d.remarks || (isWithdrawal ? 'Deposit withdrawn' : 'Deposit refunded'),
                debit: isWithdrawal ? round2(d.amount) : 0,
                credit: isWithdrawal ? 0 : round2(d.amount),
                payment_mode: 'Cash',
                reference_no: `DEPR-${d.id}`,
                operator_name: d.operator_name || 'Admin',
            });
        }
    }

    // 4b. Manual deposits taken (type='credit', not auto-generated by
    //     markPaid) → CREDIT "Deposit Taken". Bill-driven credits are
    //     represented instead by the bill's "Deposit Held" line (section
    //     8) — VERIFY the LIKE pattern below matches your markPaid code's
    //     actual remarks text, or this will double-count.
    {
        const args = [centreId];
        let sql = `
            SELECT sd.id, sd.seller_id, s.name, s.seller_code,
                   sd.transaction_date, sd.created_at, sd.amount, sd.remarks,
                   o.name AS operator_name
            FROM seller_deposits sd
            JOIN sellers s ON s.seller_id = sd.seller_id
            LEFT JOIN operators o ON o.operator_id = sd.operator_id
            WHERE sd.centre_id = ? AND sd.type = 'credit'
              AND (sd.remarks IS NULL OR sd.remarks NOT LIKE 'Deposit held for bill%')`;
        if (sellerId) { sql += ' AND sd.seller_id = ?'; args.push(sellerId); }
        if (uptoDate) { sql += ' AND sd.transaction_date <= ?'; args.push(uptoDate); }
        const [dep] = await pool.query(sql, args);
        for (const d of dep) {
            rows.push({
                seller_id: d.seller_id, seller_code: d.seller_code, name: d.name,
                ts: d.created_at || d.transaction_date,
                txn_date: d.transaction_date,
                type: 'deposit_taken',
                description: d.remarks || 'Deposit taken',
                debit: round2(d.amount),
                credit: 0,
                payment_mode: 'Cash',
                reference_no: `DEPT-${d.id}`,
                operator_name: d.operator_name || 'Admin',
            });
        }
    }

    // 5. Product sales → DEBIT
    {
        const args = [centreId];
        let sql = `
            SELECT ps.sale_id, ps.seller_id, s.name, s.seller_code,
                   ps.sale_date, ps.created_at, ps.total_amount, ps.quantity,
                   p.product_name, p.unit, o.name AS operator_name
            FROM product_sales ps
            JOIN sellers s ON s.seller_id = ps.seller_id
            JOIN products p ON p.product_id = ps.product_id
            LEFT JOIN operators o ON o.operator_id = ps.operator_id
            WHERE ps.centre_id = ?`;
        if (sellerId) { sql += ' AND ps.seller_id = ?'; args.push(sellerId); }
        if (uptoDate) { sql += ' AND ps.sale_date <= ?'; args.push(uptoDate); }
        const [ps] = await pool.query(sql, args);
        for (const p of ps) {
            rows.push({
                seller_id: p.seller_id, seller_code: p.seller_code, name: p.name,
                ts: p.created_at || p.sale_date,
                txn_date: p.sale_date,
                type: 'product_purchase',
                description: `${p.product_name || 'Product'} · ${parseFloat(p.quantity).toFixed(2)} ${p.unit || ''}`,
                debit: round2(p.total_amount),
                credit: 0,
                payment_mode: '—',
                reference_no: `PRD-${p.sale_id}`,
                operator_name: p.operator_name || 'Admin',
            });
        }
    }

    // 6. Cattle feed sales → DEBIT
    {
        const args = [centreId];
        let sql = `
            SELECT cfs.sale_id, cfs.seller_id, s.name, s.seller_code,
                   cfs.sale_date, cfs.created_at, cfs.total_amount, cfs.quantity,
                   cf.feed_name, o.name AS operator_name
            FROM cattle_feed_sales cfs
            JOIN sellers s ON s.seller_id = cfs.seller_id
            JOIN cattle_feeds cf ON cf.feed_id = cfs.feed_id
            LEFT JOIN operators o ON o.operator_id = cfs.operator_id
            WHERE cfs.centre_id = ?`;
        if (sellerId) { sql += ' AND cfs.seller_id = ?'; args.push(sellerId); }
        if (uptoDate) { sql += ' AND cfs.sale_date <= ?'; args.push(uptoDate); }
        const [cfs] = await pool.query(sql, args);
        for (const f of cfs) {
            rows.push({
                seller_id: f.seller_id, seller_code: f.seller_code, name: f.name,
                ts: f.created_at || f.sale_date,
                txn_date: f.sale_date,
                type: 'cattle_feed_purchase',
                description: `${f.feed_name || 'Cattle feed'} · ${parseFloat(f.quantity).toFixed(2)}`,
                debit: round2(f.total_amount),
                credit: 0,
                payment_mode: '—',
                reference_no: `CF-${f.sale_id}`,
                operator_name: f.operator_name || 'Admin',
            });
        }
    }

    // 7. Walk-in sales attributed to a seller (they bought milk over the
    //    counter) → DEBIT
    {
        const args = [centreId];
        let sql = `
            SELECT ws.sale_id, ws.seller_id, s.name, s.seller_code,
                   ws.sale_date, ws.created_at, ws.total_amount,
                   ws.milk_type, ws.shift, ws.payment_mode, o.name AS operator_name
            FROM walkin_sales ws
            JOIN sellers s ON s.seller_id = ws.seller_id
            LEFT JOIN operators o ON o.operator_id = ws.operator_id
            WHERE ws.centre_id = ? AND ws.seller_id IS NOT NULL`;
        if (sellerId) { sql += ' AND ws.seller_id = ?'; args.push(sellerId); }
        if (uptoDate) { sql += ' AND ws.sale_date <= ?'; args.push(uptoDate); }
        const [ws] = await pool.query(sql, args);
        for (const w of ws) {
            rows.push({
                seller_id: w.seller_id, seller_code: w.seller_code, name: w.name,
                ts: w.created_at || w.sale_date,
                txn_date: w.sale_date,
                type: 'walkin_purchase',
                description: `Milk bought (walk-in) · ${w.milk_type} · ${w.shift}`,
                debit: round2(w.total_amount),
                credit: 0,
                payment_mode: (w.payment_mode || 'cash').toUpperCase(),
                reference_no: `WI-${w.sale_id}`,
                operator_name: w.operator_name || 'Admin',
            });
        }
    }

    // 8. Settled bills (seller_payments) → up to 3 DEBIT lines each
    {
        const args = [centreId];
        let sql = `
            SELECT sp.id, sp.seller_id, s.name, s.seller_code, s.bank_account,
                   sp.paid_at, sp.bill_no, sp.deposit_amount, sp.installment_cut,
                   sp.cash_paid, o.name AS operator_name
            FROM seller_payments sp
            JOIN sellers s ON s.seller_id = sp.seller_id
            LEFT JOIN operators o ON o.operator_id = sp.operator_id
            WHERE sp.centre_id = ? AND sp.paid_at IS NOT NULL`;
        if (sellerId) { sql += ' AND sp.seller_id = ?'; args.push(sellerId); }
        if (uptoDate) { sql += ' AND sp.paid_at <= ?'; args.push(`${uptoDate} 23:59:59`); }
        const [bills] = await pool.query(sql, args);
        for (const b of bills) {
            const common = {
                seller_id: b.seller_id, seller_code: b.seller_code, name: b.name,
                ts: b.paid_at, txn_date: b.paid_at,
                reference_no: b.bill_no, operator_name: b.operator_name || 'Admin',
            };
            if (parseFloat(b.deposit_amount || 0) > 0) {
                rows.push({
                    ...common, type: 'deposit_held',
                    description: `Deposit held for bill ${b.bill_no}`,
                    debit: round2(b.deposit_amount), credit: 0, payment_mode: 'Adjusted',
                });
            }
            if (parseFloat(b.installment_cut || 0) > 0) {
                rows.push({
                    ...common, type: 'advance_recovered',
                    description: `Advance installment recovered for bill ${b.bill_no}`,
                    debit: round2(b.installment_cut), credit: 0, payment_mode: 'Adjusted',
                });
            }
            rows.push({
                ...common, type: 'cash_paid',
                description: `Cash settlement for bill ${b.bill_no}`,
                debit: round2(b.cash_paid), credit: 0,
                payment_mode: b.bank_account ? 'NEFT' : 'Cash',
            });
        }
    }

    return rows;
}

// Sorts rows chronologically and stamps a running balance per seller_id.
function withRunningBalance(rows) {
    const sorted = [...rows].sort((a, b) => new Date(a.ts) - new Date(b.ts));
    const balances = {};
    for (const r of sorted) {
        const prev = balances[r.seller_id] || 0;
        const next = round2(prev + (r.credit || 0) - (r.debit || 0));
        balances[r.seller_id] = next;
        r.running_balance = next;
        r.type_label = TYPE_LABELS[r.type] || r.type;
    }
    return sorted;
}

// ── GET /api/ledger ──────────────────────────────────────────────────────
// Query params: seller_id?, from?, to?, type?, search?, page=1, limit=25
// If seller_id is omitted, returns a combined ledger across all farmers in
// the centre (used by the main Farmer Ledger table).
exports.getLedger = async (req, res) => {
    try {
        const centreId = req.user.centre_id;
        const {
            seller_id, from, to, type, search,
            page = 1, limit = 25,
        } = req.query;

        // Full history up to `to` (or today) is needed to compute correct
        // running balances even when the visible window starts later.
        const uptoDate = to || new Date().toISOString().split('T')[0];

        const raw = await fetchRawLedgerRows(centreId, {
            sellerId: seller_id || null,
            uptoDate,
        });
        let all = withRunningBalance(raw);

        // Opening balance = running balance immediately before `from`
        let openingBalance = 0;
        if (from) {
            const before = all.filter(r => new Date(r.txn_date) < new Date(from + 'T00:00:00'));
            if (seller_id) {
                openingBalance = before.length
                    ? before[before.length - 1].running_balance
                    : 0;
            }
        }

        // Visible window filter
        if (from) all = all.filter(r => new Date(r.txn_date) >= new Date(from + 'T00:00:00'));
        if (to) all = all.filter(r => new Date(r.txn_date) <= new Date(to + 'T23:59:59'));
        if (type) all = all.filter(r => r.type === type);
        if (search) {
            const q = search.toLowerCase();
            all = all.filter(r =>
                r.name.toLowerCase().includes(q) ||
                (r.seller_code || '').toLowerCase().includes(q) ||
                (r.reference_no || '').toLowerCase().includes(q) ||
                (r.description || '').toLowerCase().includes(q)
            );
        }

        // Most recent first for display
        all.sort((a, b) => new Date(b.ts) - new Date(a.ts));

        const total = all.length;
        const totalCredit = round2(all.reduce((s, r) => s + (r.credit || 0), 0));
        const totalDebit = round2(all.reduce((s, r) => s + (r.debit || 0), 0));
        const closingBalance = all.length
            ? all.reduce((latest, r) => new Date(r.ts) > new Date(latest.ts) ? r : latest).running_balance
            : openingBalance;

        const start = (parseInt(page) - 1) * parseInt(limit);
        const paged = all.slice(start, start + parseInt(limit));

        res.json({
            rows: paged,
            total,
            page: parseInt(page),
            limit: parseInt(limit),
            opening_balance: openingBalance,
            closing_balance: closingBalance,
            total_credit: totalCredit,
            total_debit: totalDebit,
        });
    } catch (err) {
        console.error('getLedger error:', err);
        res.status(500).json({ message: 'Server error', error: err.message });
    }
};

// ── GET /api/ledger/farmer/:seller_id ───────────────────────────────────
// Farmer master info + current live balances, for the detail page header.
exports.getFarmerInfo = async (req, res) => {
    try {
        const centreId = req.user.centre_id;
        const { seller_id } = req.params;

        const [[seller]] = await pool.query(
            `SELECT seller_id, seller_code, name, mobile, seller_type, milk_type,
                    address, pincode, bank_account, bank_name, account_holder_name,
                    ifsc_code, branch_name, advance_enabled, advance_deduction,
                    deposit_enabled, deposit_per_litre, is_active, created_at
             FROM sellers WHERE seller_id = ? AND centre_id = ?`,
            [seller_id, centreId]
        );
        if (!seller) return res.status(404).json({ message: 'Farmer not found.' });

        const [[advRow]] = await pool.query(
            `SELECT COALESCE(SUM(CASE WHEN type='given' THEN amount ELSE 0 END),0) -
                    COALESCE(SUM(CASE WHEN type='received' THEN amount ELSE 0 END),0) AS balance
             FROM cash_advance WHERE seller_id = ? AND centre_id = ?`,
            [seller_id, centreId]
        );
        const [[depRow]] = await pool.query(
            `SELECT COALESCE(SUM(CASE WHEN type='credit' THEN amount ELSE 0 END),0) -
                    COALESCE(SUM(CASE WHEN type='debit' THEN amount ELSE 0 END),0) AS balance
             FROM seller_deposits WHERE seller_id = ? AND centre_id = ?`,
            [seller_id, centreId]
        );
        const [[milkRow]] = await pool.query(
            `SELECT COALESCE(SUM(quantity),0) AS total_qty, COALESCE(SUM(total_amount),0) AS total_amount,
                    COUNT(*) AS total_entries, MAX(entry_date) AS last_entry_date
             FROM milk_entries WHERE seller_id = ? AND centre_id = ?`,
            [seller_id, centreId]
        );

        // Running balance (all-time) via the same engine used for the ledger.
        const raw = await fetchRawLedgerRows(centreId, { sellerId: seller_id });
        const withBal = withRunningBalance(raw);
        const currentBalance = withBal.length ? withBal[withBal.length - 1].running_balance : 0;

        res.json({
            seller,
            advance_balance: parseFloat(advRow.balance || 0),
            deposit_balance: parseFloat(depRow.balance || 0),
            total_milk_qty: parseFloat(milkRow.total_qty || 0),
            total_milk_amount: parseFloat(milkRow.total_amount || 0),
            total_milk_entries: milkRow.total_entries,
            last_entry_date: milkRow.last_entry_date,
            current_balance: currentBalance,
        });
    } catch (err) {
        console.error('getFarmerInfo error:', err);
        res.status(500).json({ message: 'Server error', error: err.message });
    }
};

// ── GET /api/ledger/farmer/:seller_id/milk-entries ──────────────────────
// Milk entries for a farmer, optionally bucketed by day/week/month/year.
exports.getFarmerMilkEntries = async (req, res) => {
    try {
        const centreId = req.user.centre_id;
        const { seller_id } = req.params;
        const { from, to } = req.query;

        const args = [seller_id, centreId];
        let sql = `SELECT * FROM milk_entries WHERE seller_id = ? AND centre_id = ?`;
        if (from) { sql += ' AND entry_date >= ?'; args.push(from); }
        if (to) { sql += ' AND entry_date <= ?'; args.push(to); }
        sql += ' ORDER BY entry_date ASC, shift ASC';

        const [entries] = await pool.query(sql, args);
        res.json(entries);
    } catch (err) {
        console.error('getFarmerMilkEntries error:', err);
        res.status(500).json({ message: 'Server error', error: err.message });
    }
};

// ── GET /api/ledger/summary ─────────────────────────────────────────────
// Query params: search?, page=1, limit=25
// Returns one row per farmer with advance/deposit account totals and the
// last paid bill, plus centre-wide totals (unaffected by pagination).
exports.getFarmerSummaries = async (req, res) => {
    try {
        const centreId = req.user.centre_id;
        const { search, milk_type, page = 1, limit = 25 } = req.query;

        const searchClause = search ? `AND (
            s.name LIKE ? OR s.seller_code LIKE ? OR s.mobile LIKE ?
        )` : '';
        const searchArgs = search ? Array(3).fill(`%${search}%`) : [];

        const milkTypeClause = milk_type ? `AND s.milk_type = ?` : '';
        const milkTypeArgs = milk_type ? [milk_type] : [];

        // Total farmer count (for pagination), respecting search filter.
        const [[{ cnt }]] = await pool.query(
            `SELECT COUNT(*) AS cnt FROM (
                SELECT s.seller_id,
                    COALESCE(adv_given.total, 0)    AS advance_credit,
                    COALESCE(adv_received.total, 0) AS advance_debit,
                    COALESCE(dep_credit.total, 0)   AS deposit_credit,
                    COALESCE(dep_debit.total, 0)    AS deposit_debit,
                    lastbill.bill_no                AS last_bill_no
                FROM sellers s
                LEFT JOIN (
                    SELECT seller_id, SUM(amount) AS total
                    FROM cash_advance WHERE centre_id = ? AND type = 'given'
                    GROUP BY seller_id
                ) adv_given ON adv_given.seller_id = s.seller_id
                LEFT JOIN (
                    SELECT seller_id, SUM(amount) AS total
                    FROM cash_advance WHERE centre_id = ? AND type = 'received'
                    GROUP BY seller_id
                ) adv_received ON adv_received.seller_id = s.seller_id
                LEFT JOIN (
                    SELECT seller_id, SUM(amount) AS total
                    FROM seller_deposits WHERE centre_id = ? AND type = 'credit'
                    GROUP BY seller_id
                ) dep_credit ON dep_credit.seller_id = s.seller_id
                LEFT JOIN (
                    SELECT seller_id, SUM(amount) AS total
                    FROM seller_deposits WHERE centre_id = ? AND type = 'debit'
                    GROUP BY seller_id
                ) dep_debit ON dep_debit.seller_id = s.seller_id
                LEFT JOIN (
                    SELECT sp1.seller_id, sp1.bill_no
                    FROM seller_payments sp1
                    WHERE sp1.centre_id = ? AND sp1.paid_at IS NOT NULL
                      AND sp1.paid_at = (
                            SELECT MAX(sp2.paid_at) FROM seller_payments sp2
                            WHERE sp2.seller_id = sp1.seller_id
                              AND sp2.centre_id = ?
                              AND sp2.paid_at IS NOT NULL
                      )
                ) lastbill ON lastbill.seller_id = s.seller_id
                WHERE s.centre_id = ? ${searchClause} ${milkTypeClause}
                HAVING NOT (
                    advance_credit = 0 AND advance_debit = 0 AND
                    deposit_credit = 0 AND deposit_debit = 0 AND
                    last_bill_no IS NULL
                )
            ) t`,
            [centreId, centreId, centreId, centreId, centreId, centreId, centreId, ...searchArgs, ...milkTypeArgs]
        );
        const start = (parseInt(page) - 1) * parseInt(limit);

        const [rows] = await pool.query(
            `SELECT
                s.seller_id, s.seller_code, s.name, s.mobile, s.is_active,
 
                COALESCE(adv_given.total, 0)    AS advance_credit,
                COALESCE(adv_received.total, 0) AS advance_debit,
 
                COALESCE(dep_credit.total, 0)   AS deposit_credit,
                COALESCE(dep_debit.total, 0)    AS deposit_debit,
 
                lastbill.bill_no        AS last_bill_no,
                lastbill.paid_at        AS last_bill_paid_at,
                lastbill.deposit_amount AS last_bill_deposit_amount,
                lastbill.installment_cut AS last_bill_installment_cut,
                lastbill.cash_paid      AS last_bill_cash_paid
 
             FROM sellers s
 
             -- Advances given to the farmer (increases what they owe us)
             LEFT JOIN (
                SELECT seller_id, SUM(amount) AS total
                FROM cash_advance
                WHERE centre_id = ? AND type = 'given'
                GROUP BY seller_id
             ) adv_given ON adv_given.seller_id = s.seller_id
 
             -- Advances repaid/recovered (decreases what they owe us)
             LEFT JOIN (
                SELECT seller_id, SUM(amount) AS total
                FROM cash_advance
                WHERE centre_id = ? AND type = 'received'
                GROUP BY seller_id
             ) adv_received ON adv_received.seller_id = s.seller_id
 
             -- Deposits taken/held (increases deposit we hold)
             LEFT JOIN (
                SELECT seller_id, SUM(amount) AS total
                FROM seller_deposits
                WHERE centre_id = ? AND type = 'credit'
                GROUP BY seller_id
             ) dep_credit ON dep_credit.seller_id = s.seller_id
 
             -- Deposits refunded/withdrawn (decreases deposit we hold)
             LEFT JOIN (
                SELECT seller_id, SUM(amount) AS total
                FROM seller_deposits
                WHERE centre_id = ? AND type = 'debit'
                GROUP BY seller_id
             ) dep_debit ON dep_debit.seller_id = s.seller_id
 
             -- Most recent settled bill per farmer
             LEFT JOIN (
                SELECT sp1.seller_id, sp1.bill_no, sp1.paid_at,
                       sp1.deposit_amount, sp1.installment_cut, sp1.cash_paid
                FROM seller_payments sp1
                WHERE sp1.centre_id = ?
                  AND sp1.paid_at IS NOT NULL
                  AND sp1.paid_at = (
                        SELECT MAX(sp2.paid_at) FROM seller_payments sp2
                        WHERE sp2.seller_id = sp1.seller_id
                          AND sp2.centre_id = ?
                          AND sp2.paid_at IS NOT NULL
                  )
             ) lastbill ON lastbill.seller_id = s.seller_id
 
             WHERE s.centre_id = ? ${searchClause} ${milkTypeClause}
             HAVING NOT (
                advance_credit = 0 AND
                advance_debit = 0 AND
                deposit_credit = 0 AND
                deposit_debit = 0 AND
                last_bill_no IS NULL
             )
             ORDER BY s.name ASC
             LIMIT ? OFFSET ?`,
            [
                centreId, centreId, centreId, centreId, centreId, centreId,
                centreId, ...searchArgs, ...milkTypeArgs, parseInt(limit), start,
            ]
        );

        const mapped = rows.map(r => {
            const advance_credit = round2(r.advance_credit);
            const advance_debit = round2(r.advance_debit);
            const deposit_credit = round2(r.deposit_credit);
            const deposit_debit = round2(r.deposit_debit);

            return {
                seller_id: r.seller_id,
                seller_code: r.seller_code,
                name: r.name,
                mobile: r.mobile,
                is_active: r.is_active,

                advance_credit,
                advance_debit,
                advance_balance: round2(advance_credit - advance_debit),

                deposit_credit,
                deposit_debit,
                deposit_balance: round2(deposit_credit - deposit_debit),

                last_bill_no: r.last_bill_no,
                last_bill_paid_at: r.last_bill_paid_at,
                last_bill_cash_paid: r.last_bill_no != null ? round2(r.last_bill_cash_paid) : null,
                last_bill_amount: r.last_bill_no != null ? round2(r.last_bill_cash_paid) : null, // amount actually paid out to the farmer
            };
        });

        // Centre-wide totals across ALL farmers (not just this page), so
        // the summary cards on the page stay accurate under pagination.
        const [[totals]] = await pool.query(
            `SELECT
                COALESCE(SUM(CASE WHEN ca.type = 'given' THEN ca.amount ELSE 0 END), 0) -
                COALESCE(SUM(CASE WHEN ca.type = 'received' THEN ca.amount ELSE 0 END), 0) AS total_advance_outstanding
             FROM cash_advance ca
             WHERE ca.centre_id = ?`,
            [centreId]
        );
        const [[depositTotals]] = await pool.query(
            `SELECT
                COALESCE(SUM(CASE WHEN sd.type = 'credit' THEN sd.amount ELSE 0 END), 0) -
                COALESCE(SUM(CASE WHEN sd.type = 'debit' THEN sd.amount ELSE 0 END), 0) AS total_deposit_held
             FROM seller_deposits sd
             WHERE sd.centre_id = ?`,
            [centreId]
        );

        res.json({
            rows: mapped,
            total: cnt,
            page: parseInt(page),
            limit: parseInt(limit),
            total_advance_outstanding: round2(totals.total_advance_outstanding),
            total_deposit_held: round2(depositTotals.total_deposit_held),
        });
    } catch (err) {
        console.error('getFarmerSummaries error:', err);
        res.status(500).json({ message: 'Server error', error: err.message });
    }
};